-- ============================================================
-- MILEAGE TABLE
-- ============================================================
create table if not exists public.mileage (
    mileage_id bigint generated by default as identity not null,
    auto_id bigint not null,
    miles integer not null,
    "date" date,
    is_active boolean not null default true,
    created_date timestamptz not null default now(),

    constraint mileage_pkey primary key (mileage_id),

    constraint mileage_auto_id_fkey
        foreign key (auto_id)
        references public.auto (auto_id)
        on delete cascade,

    constraint mileage_miles_check
        check (miles >= 0)
);

-- ============================================================
-- INDEXES
-- ============================================================
create index if not exists mileage_auto_id_idx
    on public.mileage (auto_id);

create index if not exists mileage_created_date_idx
    on public.mileage (created_date desc);

-- ============================================================
-- ROW LEVEL SECURITY
-- ============================================================
alter table public.mileage enable row level security;

-- Owner-scoped: a user may only touch mileage for autos on their own profile.
drop policy if exists mileage_rls_policy on public.mileage;
drop policy if exists mileage_owner_policy on public.mileage;
create policy mileage_owner_policy
    on public.mileage
    for all
    to authenticated
    using (
        exists (
            select 1
            from public.auto a
            join public.profile p on p.profile_id = a.profile_id
            where a.auto_id = mileage.auto_id
              and p.user_id = auth.uid()
        )
    )
    with check (
        exists (
            select 1
            from public.auto a
            join public.profile p on p.profile_id = a.profile_id
            where a.auto_id = mileage.auto_id
              and p.user_id = auth.uid()
        )
    );

notify pgrst, 'reload schema';

