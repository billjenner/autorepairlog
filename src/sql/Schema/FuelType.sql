CREATE TABLE public.fuel_type (
    fuel_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuel_type TEXT,
    notes TEXT,
    created_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- Enable Row Level Security
-- ============================================================

ALTER TABLE public.fuel_type ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- SELECT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can view all fuel logs"
ON public.fuel_type;

CREATE POLICY "Authenticated users can view all fuel logs"
ON public.fuel_type
FOR SELECT
TO authenticated
USING (true);


-- ============================================================
-- INSERT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can insert all fuel logs"
ON public.fuel_type;

CREATE POLICY "Authenticated users can insert all fuel logs"
ON public.fuel_type
FOR INSERT
TO authenticated
WITH CHECK (true);


-- ============================================================
-- UPDATE
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can update all fuel logs"
ON public.fuel_type;

CREATE POLICY "Authenticated users can update all fuel logs"
ON public.fuel_type
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);


-- ============================================================
-- DELETE
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can delete all fuel logs"
ON public.fuel_type;

CREATE POLICY "Authenticated users can delete all fuel logs"
ON public.fuel_type
FOR DELETE
TO authenticated
USING (true);