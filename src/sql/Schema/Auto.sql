create table if not exists public.auto (
    auto_id bigint generated by default as identity not null,
    profile_id bigint not null,
    "isTemplate" boolean not null default true,
    year integer,
    make text,
    model text,
    color text,
    vin text,
    purchase_date date,
    purchase_amount integer,
    last_recorded_mileage integer,
    photo_url text,
    is_active boolean not null default true,
    created_date timestamptz not null default now(),
    constraint auto_pkey primary key (auto_id),
    constraint auto_profile_id_fkey
        foreign key (profile_id)
        references public.profile (profile_id)
        on delete cascade
);

-- ============================================================
-- ROW LEVEL SECURITY
-- ============================================================
alter table public.auto enable row level security;

-- ============================================================
-- POLICIES
-- ============================================================
drop policy if exists "Users can view their own auto" on public.auto;
create policy "Users can view their own auto"
on public.auto
for select
to authenticated
using (
    exists (
        select 1
        from public.profile p
        where p.profile_id = auto.profile_id
          and p.user_id = auth.uid()
    )
);

drop policy if exists "Users can create their own auto" on public.auto;
