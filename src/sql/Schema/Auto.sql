-- ============================================================
-- AUTO PHOTO STORAGE POLICIES
-- ============================================================
drop policy if exists "Users can view their own auto photos" on storage.objects;
create policy "Users can view their own auto photos"
on storage.objects
for select
to authenticated
using (
    bucket_id = 'auto-photos'
    and exists (
        select 1
        from public.auto a
        join public.profile p on p.profile_id = a.profile_id
        where p.profile_id::text = (storage.foldername(name))[1]
          and a.auto_id::text = (storage.foldername(name))[2]
          and p.user_id = auth.uid()
    )
);

drop policy if exists "Users can upload photos for their own autos" on storage.objects;
