CREATE TABLE public.profile_share (
    profile_share_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id bigint not null,
    email TEXT not null default ''::text,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- Enable Row Level Security
-- ============================================================

ALTER TABLE public.profile_share ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- SELECT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can view all profile shares"
ON public.profile_share;

CREATE POLICY "Authenticated users can view all profile shares"
ON public.profile_share
FOR SELECT
TO authenticated
USING (EXISTS (
    SELECT 1 FROM public.profile
    WHERE profile.profile_id = profile_share.profile_id
      AND profile.user_id = auth.uid()
));


-- ============================================================
-- INSERT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can insert all profile shares"
ON public.profile_share;

CREATE POLICY "Authenticated users can insert all profile shares"
ON public.profile_share
FOR INSERT
TO authenticated
WITH CHECK (EXISTS (
    SELECT 1 FROM public.profile
    WHERE profile.profile_id = profile_share.profile_id
      AND profile.user_id = auth.uid()
));


-- ============================================================
-- UPDATE
-- ============================================================

