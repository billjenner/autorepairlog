CREATE TABLE public.service (
    service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT REFERENCES public.schedule(schedule_id),
    name TEXT,
    notes TEXT,
    interval_miles INTEGER DEFAULT NULL,
    interval_months INTEGER DEFAULT NULL,
    interval_years  INTEGER DEFAULT NULL,
    last_date DATE DEFAULT NULL,
    last_miles INTEGER DEFAULT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.service ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all access to service"
ON public.service
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);

