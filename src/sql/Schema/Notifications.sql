CREATE TABLE IF NOT EXISTS public.notifications (
    notifications_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    profile_id bigint NOT NULL REFERENCES public.profile(profile_id),
    auto_id bigint REFERENCES public.auto(auto_id),
    service_id bigint REFERENCES public.service(service_id),

    notifications_type text NOT NULL DEFAULT 'in_app',
    subject text,
    message text,

    date_created timestamptz NOT NULL DEFAULT now(),
    date_sent timestamptz,

    delivery_status text NOT NULL DEFAULT 'pending',
    error_message text
);


-- ============================================================
-- Indexes
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_notifications_profile_id
ON public.notifications(profile_id);

CREATE INDEX IF NOT EXISTS idx_notifications_auto_id
ON public.notifications(auto_id);

CREATE INDEX IF NOT EXISTS idx_notifications_service_id
ON public.notifications(service_id);

CREATE INDEX IF NOT EXISTS idx_notifications_date_created
ON public.notifications(date_created DESC);

-- ============================================================
-- Enable Row Level Security
-- ============================================================

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- Remove existing policies
-- ============================================================

DROP POLICY IF EXISTS "Allow all access to notifications"
ON public.notifications;

DROP POLICY IF EXISTS "Authenticated users can view all notifications"
ON public.notifications;

DROP POLICY IF EXISTS "Authenticated users can insert all notifications"
ON public.notifications;

DROP POLICY IF EXISTS "Authenticated users can update all notifications"
ON public.notifications;

DROP POLICY IF EXISTS "Authenticated users can delete all notifications"
ON public.notifications;

-- ============================================================
-- SELECT
-- ============================================================

CREATE POLICY "Authenticated users can view all notifications"
ON public.notifications
FOR SELECT
TO authenticated
USING (true);

-- ============================================================
-- INSERT
-- ============================================================

CREATE POLICY "Authenticated users can insert all notifications"
ON public.notifications
FOR INSERT
TO authenticated
WITH CHECK (true);

-- ============================================================
-- UPDATE
-- ============================================================

CREATE POLICY "Authenticated users can update all notifications"
ON public.notifications
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

-- ============================================================
-- DELETE
-- ============================================================

CREATE POLICY "Authenticated users can delete all notifications"
ON public.notifications
FOR DELETE
TO authenticated
USING (true);
