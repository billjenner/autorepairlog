CREATE TABLE public.fuel_log (
    fuel_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auto_id BIGINT NOT NULL REFERENCES public.auto(auto_id),
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    prior_mileage INTEGER,
    mileage INTEGER,
    mile_per_gallon NUMERIC(8,2),
    gallons NUMERIC(8,3),
    price_per_gallon NUMERIC(8,3),
    total_cost NUMERIC(10,2),
    fuel_type TEXT,
    station TEXT,
    location TEXT,  --- not used
    is_full_tank BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    allow_notifications BOOLEAN NOT NULL DEFAULT TRUE,
    created_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- Enable Row Level Security
-- ============================================================

ALTER TABLE public.fuel_log ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- Allow all access to anon and authenticated
-- ============================================================

CREATE POLICY "Allow all access to fuel_log"
ON public.fuel_log
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);


