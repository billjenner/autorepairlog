CREATE TABLE public.station (
    station_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station TEXT,
    location TEXT,
    notes TEXT,
    created_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- Enable Row Level Security
-- ============================================================

ALTER TABLE public.station ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- SELECT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can view all stations"
ON public.station;

CREATE POLICY "Authenticated users can view all stations"
ON public.station
FOR SELECT
TO authenticated
USING (true);


-- ============================================================
-- INSERT
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can insert all stations"
ON public.station;

CREATE POLICY "Authenticated users can insert all stations"
ON public.station
FOR INSERT
TO authenticated
WITH CHECK (true);


-- ============================================================
-- UPDATE
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can update all stations"
ON public.station;

CREATE POLICY "Authenticated users can update all stations"
ON public.station
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);


-- ============================================================
-- DELETE
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can delete all stations"
ON public.station;

CREATE POLICY "Authenticated users can delete all stations"
ON public.station
FOR DELETE
TO authenticated
USING (true);