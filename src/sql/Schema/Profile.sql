-- PUBLIC.PROFILE
create table public.profile (
    profile_id bigint generated by default as identity not null,
    user_id uuid not null,
    fname text not null default ''::text,
    lname text not null default ''::text,
    admin_level numeric not null default 0,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),

    constraint profile_pkey primary key (profile_id),
    constraint profile_user_id_key unique (user_id),

    -- Link profile to the Supabase authenticated user
    constraint profile_user_id_fkey
        foreign key (user_id)
        references auth.users (id)
        on delete cascade
);

-- ============================================================
-- Add to table
-- ============================================================
ALTER TABLE public.profile
    ADD COLUMN email text NOT NULL DEFAULT ''::text,
    ADD COLUMN last_logged_in timestamptz NULL;

-- ============================================================
-- ROW LEVEL SECURITY
-- ============================================================

alter table public.profile enable row level security;

-- ============================================================
-- POLICIES
-- ============================================================

-- Users can view their own profile
create policy "Users can view their own profile"
on public.profile
for select
to authenticated
using (auth.uid() = user_id);

-- Users can update their own profile
create policy "Users can update their own profile"
on public.profile
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Users can create their own profile
create policy "Users can create their own profile"
on public.profile
for insert
to authenticated
with check (auth.uid() = user_id);

-- Admins (admin_level > 0) can view all profiles.
-- security definer avoids infinite recursion from querying profile inside its own policy.
create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1 from public.profile
        where user_id = auth.uid() and admin_level > 0
    );
$$;

create policy "Admins can view all profiles"
on public.profile
for select
to authenticated
using (public.is_admin());

